import Color from "colorjs.io";

import { alpha } from "../../components/color.js";

const SHADE = { dark: 0.25, light: 0.07 };

const RELOAD = [
	"key='org.gnome.desktop.a11y.interface high-contrast'",
	"contrast=$(gsettings get $key)",
	'gsettings set $key $([ "$contrast" = true ] && echo false || echo true)',
	"sleep 0.3",
	'gsettings set $key "$contrast"',
].join("; ");

const status = (name, source) => {
	return {
		[`${name}-bg`]: source.background,
		[`${name}-fg`]: source.foreground.normal,
		[name]: source.color,
	};
};

const area = (name, source) => {
	return {
		[`${name}-bg`]: source.background,
		[`${name}-fg`]: source.foreground.strong,
	};
};

const variables = (roles, theme) => {
	const { accent, color, scrim, shadow, surface } = roles;
	const { field, frame, panel, modal, popup } = surface;
	const shade = alpha(shadow, SHADE[theme]);

	return {
		...status("accent", accent.primary),
		...status("destructive", color.red),
		...status("success", color.green),
		...status("warning", color.yellow),
		...status("error", color.red),

		...area("window", frame),
		...area("view", field),

		...area("headerbar", frame),
		"headerbar-border": frame.foreground.strong,
		"headerbar-backdrop": frame.background,
		"headerbar-shade": shade,
		"headerbar-darker-shade": scrim,

		...area("sidebar", frame),
		"sidebar-backdrop": frame.background,
		"sidebar-border": frame.outline.silent,
		"sidebar-shade": shade,

		...area("secondary-sidebar", frame),
		"secondary-sidebar-backdrop": frame.background,
		"secondary-sidebar-border": frame.outline.silent,
		"secondary-sidebar-shade": shade,

		...area("card", panel),
		"card-shade": shade,

		...area("overview", frame),
		...area("thumbnail", modal),
		...area("dialog", modal),

		...area("popover", popup),
		"popover-shade": shade,

		...area("active-toggle", popup),

		"shade": shade,
		"scrollbar-outline": field.background,
	};
};

const tone = (color) => {
	return new Color(color).to("hct").coords[2];
};

const opacity = ({ background, foreground }, target) => {
	const goal = Math.abs(tone(target) - tone(background));
	let [low, high] = [0, 1];

	for (let step = 0; step < 20; step++) {
		const middle = (low + high) / 2;
		const mixed = alpha(foreground.strong, middle, background);
		const reached = Math.abs(tone(mixed) - tone(background));

		[low, high] = reached < goal ? [middle, high] : [low, middle];
	}

	return `${Math.round(low * 100)}%`;
};

const opacities = ({ surface }) => {
	const { frame } = surface;

	return {
		"border-opacity": opacity(frame, frame.outline.subtle),
		"dim-opacity": opacity(frame, frame.foreground.subtle),
		"disabled-opacity": opacity(frame, frame.foreground.silent),
	};
};

const legacy = (value) => {
	if (value.length !== 9) {
		return value;
	}

	const opacity = parseInt(value.slice(7), 16) / 255;

	return `alpha(${value.slice(0, 7)}, ${opacity.toFixed(2)})`;
};

const define = (colors, format = (value) => value) => {
	return Object.entries(colors).map(([key, value]) => {
		return `@define-color ${key.replaceAll("-", "_")}_color ${format(value)};`;
	});
};

const root = (colors, levels) => {
	return [
		":root {",
		...Object.entries(colors).map(([key, value]) => {
			return `\t--${key}-color: ${value};`;
		}),
		...Object.entries(levels).map(([key, value]) => {
			return `\t--${key}: ${value};`;
		}),
		"}",
	];
};

const indent = (lines) => {
	return lines.map((line) => (line === "" ? line : `\t${line}`));
};

const block = ({ roles }, theme) => {
	const colors = variables(roles, theme);

	return [...define(colors), "", ...root(colors, opacities(roles))];
};

const gtk4 = (scheme, name) => {
	return [
		`/* ${name}, generated by Lumen */`,
		"",
		...block(scheme.theme.light, "light"),
		"",
		"@media (prefers-color-scheme: dark) {",
		...indent(block(scheme.theme.dark, "dark")),
		"}",
		"",
	].join("\n");
};

const gtk3 = (scheme, name, theme) => {
	const colors = variables(scheme.theme[theme].roles, theme);

	return [
		`/* ${name}, generated by Lumen (${theme}) */`,
		"",
		...define(colors, legacy),
		"",
	].join("\n");
};

export default (scheme, { name, theme, config }) => {
	const adwaita = theme === "dark" ? "adw-gtk3-dark" : "adw-gtk3";

	return {
		directory: config,
		files: [
			{ path: "gtk-4.0/lumen.css", data: gtk4(scheme, name) },
			{ path: "gtk-3.0/lumen.css", data: gtk3(scheme, name, theme) },
		],
		command: `gsettings set org.gnome.desktop.interface gtk-theme ${adwaita}; ${RELOAD}`,
	};
};
