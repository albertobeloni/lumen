import path from "node:path";

import { flatten } from "../../components/color.js";

const theme = (name, { accent, ansi, base, color, surface, ui }) => {
	const { field, frame } = surface;
	const { primary, secondary } = accent;
	const { variant } = base;

	return `# ${name}, generated by Lumen

foreground ${field.foreground.normal}
background ${field.background}
selection_foreground none
selection_background ${flatten(ui.selection, field.background)}

cursor ${ui.cursor}
cursor_text_color ${field.background}
cursor_trail_color ${field.foreground.subtle}

url_color ${primary.color}
visual_bell_color ${color.yellow.container.background}

active_border_color ${ui.focus}
inactive_border_color ${field.outline.silent}
bell_border_color ${color.yellow.color}

tab_bar_background ${frame.background}
tab_bar_margin_color ${frame.background}
active_tab_foreground ${field.foreground.strong}
active_tab_background ${field.background}
inactive_tab_foreground ${frame.foreground.subtle}
inactive_tab_background ${frame.background}

mark1_foreground ${primary.container.foreground.strong}
mark1_background ${primary.container.background}
mark2_foreground ${variant.container.foreground.strong}
mark2_background ${variant.container.background}
mark3_foreground ${secondary.container.foreground.strong}
mark3_background ${secondary.container.background}

scrollbar_handle_color ${field.foreground.subtle}
scrollbar_track_color ${field.background}

color0 ${ansi.black.normal}
color1 ${ansi.red.normal}
color2 ${ansi.green.normal}
color3 ${ansi.yellow.normal}
color4 ${ansi.blue.normal}
color5 ${ansi.magenta.normal}
color6 ${ansi.cyan.normal}
color7 ${ansi.white.normal}
color8 ${ansi.black.strong}
color9 ${ansi.red.strong}
color10 ${ansi.green.strong}
color11 ${ansi.yellow.strong}
color12 ${ansi.blue.strong}
color13 ${ansi.magenta.strong}
color14 ${ansi.cyan.strong}
color15 ${ansi.white.strong}
`;
};

export default (scheme, { name, config }) => {
	const dark = theme(`${name} Dark`, scheme.theme.dark.roles);
	const light = theme(`${name} Light`, scheme.theme.light.roles);

	return {
		directory: path.join(config, "kitty"),
		files: [
			{ path: "dark-theme.auto.conf", data: dark },
			{ path: "light-theme.auto.conf", data: light },
			{ path: "no-preference-theme.auto.conf", data: light },
		],
		command: "pkill -USR1 -x kitty || true",
	};
};
