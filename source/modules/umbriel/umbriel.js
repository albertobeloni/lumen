import path from "node:path";

import { alpha } from "../../components/color.js";

const colors = ({ accent, color, shadow, surface }) => {
	const { field, frame, panel, popup } = surface;
	const { primary, secondary } = accent;
	const { red, yellow } = color;

	return `[colors]
background = "${popup.background}"
text_primary = "${popup.foreground.strong}"
text_muted = "${popup.foreground.subtle}"
accent_primary = "${primary.color}"
accent_secondary = "${secondary.color}"
warning = "${yellow.color}"
error = "${red.color}"
insert_hint = "${alpha(primary.color, 0.25)}"
backdrop = "${field.background}"
shadow = "${shadow}"

[colors.border]
focused = "${secondary.container.outline.silent}"
unfocused = "${frame.outline.subtle}"
outer = "${field.background}"

[colors.overview]
background_tint = "${alpha(field.background, 0.3)}"
workspace_background = "${alpha(field.background, 0.25)}"
badge = "${primary.color}"

[colors.tab_bar]
background = "${frame.background}"
text = "${frame.foreground.subtle}"
active = "${primary.background}"
active_text = "${primary.foreground.normal}"
active_unfocused = "${panel.background}"
active_unfocused_text = "${panel.foreground.normal}"
urgent = "${red.background}"
urgent_text = "${red.foreground.normal}"

[colors.title_bar]
background = "${frame.background}"
background_unfocused = "${field.background}"
text = "${frame.foreground.strong}"
text_unfocused = "${frame.foreground.subtle}"
close = "${red.background}"
close_glyph = "${frame.foreground.normal}"
close_glyph_hover = "${frame.foreground.strong}"
maximize = "${primary.background}"
maximize_glyph = "${frame.foreground.normal}"
maximize_glyph_hover = "${frame.foreground.strong}"
minimize = "${yellow.background}"
minimize_glyph = "${frame.foreground.normal}"
minimize_glyph_hover = "${frame.foreground.strong}"
`;
};

export default (scheme, { name, theme, config }) => {
	const body = colors(scheme.theme[theme].roles);
	const data = `# ${name}, generated by Lumen (${theme})\n\n${body}`;

	return {
		directory: path.join(config, "umbriel", "components"),
		files: [{ path: "lumen.toml", data }],
	};
};
