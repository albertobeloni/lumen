import path from "node:path";

import { alpha } from "../../components/color.js";

const colors = (roles) => {
	const { accent, base, color, shadow, status, surface, ui } = roles;
	const { field, frame, panel, popup } = surface;
	const { primary } = accent;
	const { variant } = base;
	const { green, red, yellow } = color;

	return `[colors]
background = "${popup.background}"
text_primary = "${popup.foreground.strong}"
text_muted = "${popup.foreground.subtle}"
accent_primary = "${primary.color}"
accent_secondary = "${variant.color}"
warning = "${status.caution.color}"
error = "${status.critical.color}"
insert_hint = "${primary.tint.strong}"
backdrop = "${field.background}"
shadow = "${shadow}"

[colors.border]
focused = "${frame.outline.normal}"
unfocused = "${frame.outline.subtle}"
outer = "${field.background}"

[colors.overview]
background_tint = "${alpha(field.background, 0.3)}"
workspace_background = "${alpha(field.background, 0.25)}"
badge = "${primary.color}"

[colors.tab_bar]
background = "${frame.background}"
text = "${frame.foreground.normal}"
active = "${field.background}"
active_text = "${field.foreground.strong}"
active_unfocused = "${panel.background}"
active_unfocused_text = "${panel.foreground.normal}"
urgent = "${status.caution.background}"
urgent_text = "${status.caution.foreground.normal}"

[colors.title_bar]
background = "${frame.outline.normal}"
background_unfocused = "${frame.outline.subtle}"
text = "${frame.container.foreground.normal}"
text_unfocused = "${frame.container.foreground.subtle}"
close = "${red.background}"
close_glyph = "${red.foreground.normal}"
close_glyph_hover = "${red.foreground.strong}"
maximize = "${green.background}"
maximize_glyph = "${green.foreground.normal}"
maximize_glyph_hover = "${green.foreground.strong}"
minimize = "${yellow.background}"
minimize_glyph = "${yellow.foreground.normal}"
minimize_glyph_hover = "${yellow.foreground.strong}"
`;
};

export default (scheme, { name, theme, config }) => {
	const body = colors(scheme.theme[theme].roles);
	const data = `# ${name}, generated by Lumen (${theme})\n\n${body}`;

	return {
		directory: path.join(config, "umbriel", "components"),
		files: [{ path: "lumen.toml", data }],
	};
};
