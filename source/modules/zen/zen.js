import os from "node:os";
import path from "node:path";

import { existsSync, readFileSync } from "node:fs";

import { opacities, variables } from "../gtk/gtk.js";

const ROOTS = [
	path.join(os.homedir(), ".var", "app", "app.zen_browser.zen", ".zen"),
	path.join(os.homedir(), ".zen"),
];

const sections = (text) => {
	const result = {};
	let current;

	for (const line of text.split("\n")) {
		const header = line.match(/^\[(.+)\]$/);
		const pair = line.match(/^([^=]+)=(.*)$/);

		if (header) {
			current = result[header[1]] = {};
		} else if (pair && current) {
			current[pair[1].trim()] = pair[2].trim();
		}
	}

	return result;
};

const profile = () => {
	for (const root of ROOTS) {
		const file = path.join(root, "profiles.ini");

		if (!existsSync(file)) {
			continue;
		}

		const entries = Object.entries(sections(readFileSync(file, "utf8")));
		const install = entries.find(([name]) => name.startsWith("Install"));
		const fallback = entries.find(([, values]) => values.Default === "1");
		const relative = install?.[1].Default ?? fallback?.[1].Path;

		if (relative) {
			return path.join(root, relative);
		}
	}

	return undefined;
};

const declare = (values, suffix, indent) => {
	return Object.entries(values).map(([key, value]) => {
		return `${indent}\t--lumen-${key}${suffix}: ${value};`;
	});
};

const root = ({ roles }, theme, indent) => {
	return [
		`${indent}:root {`,
		...declare(variables(roles, theme), "-color", indent),
		...declare(opacities(roles), "", indent),
		`${indent}}`,
	];
};

const stylesheet = (scheme, name) => {
	return [
		`/* ${name}, generated by Lumen */`,
		"",
		...root(scheme.theme.light, "light", ""),
		"",
		"@media (prefers-color-scheme: dark) {",
		...root(scheme.theme.dark, "dark", "\t"),
		"}",
		"",
	].join("\n");
};

export default (scheme, { name }) => {
	const folder = profile();

	return {
		directory: folder && path.join(folder, "chrome"),
		files: [{ path: "lumen.css", data: stylesheet(scheme, name) }],
	};
};
