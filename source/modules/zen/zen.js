import os from "node:os";
import path from "node:path";

import { existsSync, readFileSync } from "node:fs";

const ROOTS = [
	path.join(os.homedir(), ".var", "app", "app.zen_browser.zen", ".zen"),
	path.join(os.homedir(), ".zen"),
];

const sections = (text) => {
	const result = {};
	let current;

	for (const line of text.split("\n")) {
		const header = line.match(/^\[(.+)\]$/);
		const pair = line.match(/^([^=]+)=(.*)$/);

		if (header) {
			current = result[header[1]] = {};
		} else if (pair && current) {
			current[pair[1].trim()] = pair[2].trim();
		}
	}

	return result;
};

const profile = () => {
	for (const root of ROOTS) {
		const file = path.join(root, "profiles.ini");

		if (!existsSync(file)) {
			continue;
		}

		const entries = Object.entries(sections(readFileSync(file, "utf8")));
		const install = entries.find(([name]) => name.startsWith("Install"));
		const fallback = entries.find(([, values]) => values.Default === "1");
		const relative = install?.[1].Default ?? fallback?.[1].Path;

		if (relative) {
			return path.join(root, relative);
		}
	}

	return undefined;
};

const variables = ({ accent, shadow, status, surface, ui }) => {
	const { field, frame, panel, popup } = surface;
	const { primary } = accent;

	return {
		"window-background": frame.background,
		"window-foreground": frame.foreground.strong,
		"window-muted": frame.foreground.subtle,
		"window-faint": frame.foreground.silent,
		"window-border": frame.outline.silent,
		"window-hover": frame.overlay.silent,
		"window-selected": frame.overlay.normal,

		"content-background": field.background,
		"content-foreground": field.foreground.normal,
		"content-muted": field.foreground.subtle,
		"content-border": field.outline.silent,

		"entry-background": panel.background,
		"entry-foreground": panel.foreground.normal,

		"card-background": panel.background,
		"card-foreground": panel.foreground.normal,

		"popup-background": popup.background,
		"popup-foreground": popup.foreground.normal,
		"popup-border": popup.outline.silent,
		"popup-hover": popup.overlay.silent,
		"popup-selected": popup.overlay.normal,

		"accent": primary.color,
		"accent-background": primary.background,
		"accent-foreground": primary.foreground.normal,

		"selection": ui.selection,
		"focus": ui.focus,
		"match": ui.match.all,
		"link": ui.link.normal,
		"link-visited": ui.link.visited,

		"critical": status.critical.color,
		"critical-background": status.critical.tint.subtle,
		"caution": status.caution.color,
		"caution-background": status.caution.tint.subtle,
		"success": status.success.color,
		"success-background": status.success.tint.subtle,
		"notice": status.notice.color,
		"notice-background": status.notice.tint.subtle,

		"shadow": shadow,
	};
};

const root = (roles, indent) => {
	const lines = Object.entries(variables(roles)).map(([key, value]) => {
		return `${indent}\t--lumen-${key}: ${value};`;
	});

	return [`${indent}:root {`, ...lines, `${indent}}`];
};

const stylesheet = (scheme, name) => {
	return [
		`/* ${name}, generated by Lumen */`,
		"",
		...root(scheme.theme.light.roles, ""),
		"",
		"@media (prefers-color-scheme: dark) {",
		...root(scheme.theme.dark.roles, "\t"),
		"}",
		"",
	].join("\n");
};

export default (scheme, { name }) => {
	const folder = profile();

	return {
		directory: folder && path.join(folder, "chrome"),
		files: [{ path: "lumen.css", data: stylesheet(scheme, name) }],
	};
};
